"""Generate readable C++ sources for the game data tables in SLUS_209.11.

    python tools/gen_tables.py

Reads the tables from game/SLUS_209.11 and writes:

    source/include/nocturne/data/ids.hpp    devil::, skill::, item:: ID constants and the Race enum
    source/src/data/*_table.cpp             one file per table, one entry per record

Names come from reference/names/*.tsv. Only non-zero fields are written, in
declaration order (C++20 designated initializers). source/tests/tables checks
that the compiled tables are byte-identical to the executable.

The record layouts below must match source/include/nocturne/data/records.hpp.
"""
