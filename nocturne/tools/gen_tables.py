# --- names ------------------------------------------------------------------------


def load_names(file):
    names = {}
    for line in (ROOT / "reference" / "names" / file).read_text(encoding="utf-8").splitlines()[1:]:
        key, name = line.split("\t")
        names[int(key, 16)] = name
    return names


def identifier(name):
    name = name.replace("&", " And ").replace("'", "")
    words = re.split(r"[^0-9A-Za-z]+", name)
    ident = "".join(w[:1].upper() + w[1:] for w in words if w)
    return ("_" + ident) if ident[:1].isdigit() else ident


def identifiers(names, valid_ids, fallback):
    """id -> C++ identifier, unique, with a fallback for unnamed IDs."""
    result, used = {}, {}
    for i in valid_ids:
        base = identifier(names[i]) if i in names else f"{fallback}{i:03X}"
        used.setdefault(base, []).append(i)
        result[i] = base
    for base, ids in used.items():
        if len(ids) > 1:
            for i in ids:
                result[i] = f"{base}_{i:03X}"
    return result


devil_names = load_names("devils.tsv")
