skill_names.setdefault(0, "Normal Attack")
item_names = load_names("items.tsv")
race_names = load_names("races.tsv")

DEVIL_ID = identifiers(devil_names, range(1, 384), "Devil")
SKILL_ID = identifiers(skill_names, sorted(set(range(0x200)) | set(skill_names)), "Skill")
ITEM_ID = identifiers(item_names, sorted(item_names), "Item")
RACE_ID = identifiers(race_names, sorted(race_names), "Race")

# --- formatting -------------------------------------------------------------------


def value_text(v, kind):
    if kind == "hex":
        return f"0x{v:X}" if v > 9 else str(v)
    if kind == "devil":
        return f"devil::{DEVIL_ID[v]}" if v in DEVIL_ID else f"0x{v:03X}"
    if kind == "skill":
        return f"skill::{SKILL_ID[v]}" if v in SKILL_ID else f"0x{v:03X}"
    if kind == "item":
        return f"item::{ITEM_ID[v]}" if v in ITEM_ID else str(v)
    if kind == "race":
        return f"Race::{RACE_ID[v]}" if v in RACE_ID else f"Race({v})"
    if kind == "ailments":
        parts = [f"ailment::{n}" for bit, n in AILMENTS if v & bit]
        rest = v & ~sum(bit for bit, _ in AILMENTS)
        if rest:
            parts.append(f"0x{rest:X}")
        return " | ".join(parts)
    return str(v)


def fields_text(rec):
    """Designated initializers for non-zero fields; arrays trimmed of trailing zeros."""
    parts = []
    for name, (v, kind) in rec.items():
        if isinstance(v, list):
            while v and v[-1] == 0:
                v = v[:-1]
            if v:
                parts.append(f".{name} = {{{', '.join(value_text(x, kind) for x in v)}}}")
        elif v:
            parts.append(f".{name} = {value_text(v, kind)}")
    return parts


def wrap(parts, indent, width=110):
    lines, line = [], ""
    for p in parts:
        piece = p + ","
        if line and len(indent) + len(line) + 1 + len(piece) > width:
            lines.append(indent + line)
            line = piece
        else:
            line = f"{line} {piece}" if line else piece
    if line:
        lines.append(indent + line)
    return "\n".join(lines)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")


