def generate_devils():
    base, count, stride = TABLES["devil"]
    out = [HEADER, f"// datDevilFormat, 0x{base:08X}: species data for each devil.\n",
           f"const DevilFormat kDevilFormat[{count}] = {{\n"]
    for i in range(count):
        rec = record(DEVIL, base + i * stride)
        name = devil_names.get(i, "(unnamed)")
        race = race_names.get(rec["race"][0], "-")
        out.append(f"    // 0x{i:03X} {name} ({race}, Lv {rec['level'][0]})\n")
        parts = fields_text(rec)
        out.append("    {\n" + wrap(parts, "        ") + "\n    },\n" if parts else "    {},\n")
    out.append("};\n\n} // namespace nocturne::dat\n")
    write(ROOT / "source/maniax/src/data/devil_table.cpp", "".join(out))


def generate_skills():
    base, count, stride = TABLES["skill_info"]
    out = [HEADER, f"// datSkill, 0x{base:08X}: every skill ID. skillattr is the element\n",
           "// (Attribute), type 0 active / 1 passive / -1 unused.\n",
           f"const SkillInfo kSkillInfo[{count}] = {{\n"]
    for i in range(count):
        rec = record(SKILL_INFO, base + i * stride)
        attr = rec["skillattr"][0]
        element = ATTRIBUTES[attr] if 0 <= attr < 16 else "-"
        parts = fields_text(rec)
        body = "{" + ", ".join(parts) + "}" if parts else "{}"
        out.append(f"    {body}, // 0x{i:03X} {skill_names.get(i, '(unnamed)')} ({element})\n")
    out.append("};\n\n")
    base, count, stride = TABLES["normal_skill"]
    out += [f"// datNormalSkill, 0x{base:08X}: how each active skill hits.\n",
           "// damageClass: 0 physical, 1 magic. hitlevel 255 = never misses.\n",
           f"const NormalSkill kNormalSkill[{count}] = {{\n"]
    for i in range(count):
        rec = record(NORMAL_SKILL, base + i * stride)
        out.append(f"    // 0x{i:03X} {skill_names.get(i, '(unnamed)')}\n")
        parts = fields_text(rec)
        out.append("    {\n" + wrap(parts, "        ") + "\n    },\n" if parts else "    {},\n")
    out.append("};\n\n")
    base, count, stride = TABLES["special_skill"]
    out.append(f"// datSpecialSkill, 0x{base:08X}: numbers for passive skills 0x128-0x17F.\n")
    out.append(f"const SpecialSkill kSpecialSkill[{count}] = {{\n")
    for i in range(count):
        n, m, a, b = read(base + i * stride, "4h")
        sid = 0x128 + i
        out.append(f"    {{{n}, {m}, {a}, {b}}}, // 0x{sid:03X} {skill_names.get(sid, '(unnamed)')}\n")
    out.append("};\n\n} // namespace nocturne::dat\n")
    write(ROOT / "source/maniax/src/data/skill_table.cpp", "".join(out))


def generate_encounters():
    base, count, stride = TABLES["encount"]
    out = [HEADER, f"// datEncount, 0x{base:08X}: enemy groups. Index = MainProcessData::encno.\n",
           f"const Encount kEncount[{count}] = {{\n"]
    for i in range(count):
        rec = record(ENCOUNT, base + i * stride)
        parts = fields_text(rec)
        out.append(f"    /* 0x{i:03X} */ " + ("{\n" + wrap(parts, "        ") + "\n    },\n" if parts else "{},\n"))
    out.append("};\n\n")

    base, count, stride = TABLES["encount_pack"]
    out.append(f"// datEncountPack, 0x{base:08X}: random-encounter tables per area.\n")
    out.append("// Each table: base rate, then up to 12 entries {encountid, weight, firstStrike,\n")
    out.append("// chainChance (follow-up chance %), chainEntry (follow-up entry)}.\n")
    out.append(f"const EncountPack kEncountPack[{count}] = {{\n")
    for i in range(count):
        p = base + i * stride
        header = fields_text(record(ENCOUNT_PACK_HEADER, p))
        tables = []
        for t in range(4):
            tb = p + 20 + t * 100
            normal = read(tb, "i")[0]
            ritu = [fields_text(record(ENCOUNT_RITU, tb + 4 + r * 8)) for r in range(12)]
            while ritu and not ritu[-1]:
                ritu.pop()
            inner = []
            if normal:
                inner.append(f".normalWeight = {normal}")
            if ritu:
                inner.append(".entries = {\n" + ",\n".join(
                    "                {" + ", ".join(r) + "}" for r in ritu) + ",\n            }")
            tables.append("{" + ", ".join(inner) + "}" if inner else "{}")
        while tables and tables[-1] == "{}":
            tables.pop()
        body = list(header)
        if tables:
            body.append(".enctable = {\n            " + ",\n            ".join(tables) + ",\n        }")
        out.append(f"    /* 0x{i:02X} */ " + ("{\n" + "".join(f"        {b},\n" for b in body) + "    },\n" if body else "{},\n"))
    out.append("};\n\n} // namespace nocturne::dat\n")
    write(ROOT / "source/maniax/src/data/encounter_table.cpp", "".join(out))


def affinity_text(v):
    flags = [("Weak", 0x80000000), ("Null", 0x10000), ("Repel", 0x20000), ("Drain", 0x40000), ("Flag100000", 0x100000)]
    parts = [n for n, bit in flags if v & bit]
    other = v & 0xFFFF0000 & ~sum(bit for _, bit in flags)
    rate = v & 0xFFFF
    if other:
        parts.append(f"0x{other:X}")
    if rate or not parts:
        parts.append(str(rate))
    return "|".join(parts)


def generate_affinity():
    base, count, stride = TABLES["affinity"]
    users = {}
    for i in range(1, 384):
        users.setdefault(read(TABLES["devil"][0] + i * 60 + 0x0E, "h")[0], []).append(devil_names.get(i, f"0x{i:03X}"))
    out = [HEADER, f"// Affinity table, 0x{base:08X}: one row of 16 packed affinities per\n",
           "// DevilFormat::affinityId. Each entry: damage rate in percent, plus flags\n",
           "// (Null, Repel, Drain, Weak; Flag100000 role unknown). See types.hpp Affinity.\n",
           "// Row 246 is used for petrified units, 247 for Fly.\n\n",
           "namespace {\n",
           "constexpr uint32_t Null = Affinity::Null, Repel = Affinity::Repel, Drain = Affinity::Drain,\n",
           "                   Weak = Affinity::Weak, Flag100000 = Affinity::Unknown100000;\n",
           "} // namespace\n\n",
           "// " + "  ".join(a[:5].ljust(5) for a in ATTRIBUTES[:11]) + "  (11..15)\n",
           f"const uint32_t kAffinity[{count}][16] = {{\n"]
    for r in range(count):
        row = read(base + r * stride, "16I")
        label = {246: "Stone", 247: "Fly"}.get(r, ", ".join(users.get(r, [])[:4]) + (" ..." if len(users.get(r, [])) > 4 else ""))
        cells = ", ".join(affinity_text(v) for v in row)
        out.append(f"    /* {r:3} */ {{{cells}}},{(' // ' + label) if label else ''}\n")
    out.append("};\n\n} // namespace nocturne::dat\n")
    write(ROOT / "source/maniax/src/data/affinity_table.cpp", "".join(out))


def growth_event_text(level, type_, param):
    parts = []
    if level: parts.append(f".targetlevel = {level}")
    if type_: parts.append(f".type = {type_}")
    if param:
        parts.append(f".param = {value_text(param, 'skill') if type_ == 1 else str(param)}")
    return "{" + ", ".join(parts) + "}"


def generate_growth():
    base, stride, count = 0x333CF8, 102, 384
    out = [HEADER, f"// fclSkillTbl, 0x{base:08X}: per devil, stat-growth weights and level events.\n",
           "// Event type 1 learns skill `param` at `targetlevel`; 7 marks evolution.\n",
           f"const DevilGrowth kDevilGrowth[{count}] = {{\n"]
    for i in range(count):
        p = base + i * stride
        grow = list(read(p, "6b"))
        events = [read(p + 6 + 4 * k, "bBH") for k in range(24)]
        while events and events[-1] == (0, 0, 0):
            events.pop()
        parts = []
        if any(grow):
            parts.append(".growparam = {" + ", ".join(map(str, grow)) + "}")
        if events:
            parts.append(".event = {\n" + "".join(f"            {growth_event_text(*e)},\n" for e in events) + "        }")
        out.append(f"    // 0x{i:03X} {devil_names.get(i, '(unnamed)')}\n")
        out.append("    {\n" + "".join(f"        {x},\n" for x in parts) + "    },\n" if parts else "    {},\n")
    out.append("};\n\n} // namespace nocturne::dat\n")
    write(ROOT / "source/maniax/src/data/growth_table.cpp", "".join(out))


def generate_inheritance():
    out = [HEADER, "// Evolution and skill-inheritance tables, 0x00339640-0x00339CFC.\n\n"]
    out.append("// Evolution needs the event bit set, 0x00339640.\n")
    out.append("const EvolutionRequirement kEvolutionRequirement[6] = {\n")
    for i in range(6):
        dv, bit = read(0x339640 + i * 4, "HH")
        out.append(f"    {{{value_text(dv, 'devil')}, 0x{bit:X}}},\n")
    out.append("};\n\n// fclKeisyoSkillLevel, 0x00339658: divisor for each skill's inheritance rate.\n")
    out.append("const InheritanceLevelRow kInheritanceLevel[kInheritanceLevelCount] = {\n")
    if VARIANT == "hardtype":   # 3-byte rows (InheritanceLevelPacked)
        for i in range(302):
            lo, hi, lv = read(0x339658 + i * 3, "BBB")
            out.append(f"    {{{{0x{lo:02X}, 0x{hi:02X}}}, {lv}}}, // {value_text(lo | hi << 8, 'skill')}\n")
    else:
        for i in range(227):
            sk, lv, pad = read(0x339658 + i * 4, "HBB")
            out.append(f"    {{{value_text(sk, 'skill')}, {lv}" + (f", {pad}" if pad else "") + "},\n")
    out.append("};\n\n")
    base = 0x3399E8
    unk, *attrs = read(base, "h16h")
    out.append("// Inheritance scores, 0x003399E8: base rate by devil inheritance type (rows)\n")
    out.append("// and skill element (columns).\n")
    out.append("const InheritanceScores kInheritanceScores = {\n")
    out.append(f"    {unk},\n    {{{', '.join(map(str, attrs))}}},\n    {{\n")
    for r in range(12):
        key, *scores = read(base + 34 + r * 34, "h16H")
        out.append(f"        {{{key}, {{{', '.join(map(str, scores))}}}}},\n")
    out.append("    },\n};\n\n")
