# --- reading ----------------------------------------------------------------------

elf = ELF.read_bytes()


def read(ram, fmt):
    return struct.unpack_from("<" + fmt, elf, ram - DATA_SEGMENT_DELTA)


# Field spec: (name, struct format char, count, offset, kind). kind selects how a
# value is written: num, hex, devil, skill, item, race, ailments.
def record(spec, base):
    out = {}
    for name, fmt, count, offset, kind in spec:
        values = list(read(base + offset, f"{count}{fmt}"))
        out[name] = (values if count > 1 or name.endswith("[]") else values[0], kind)
    return out


